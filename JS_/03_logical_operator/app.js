// logical operator

// logical AND
let marks = 80;

if(marks>=33 && marks>=80){
  console.log("pass");
  console.log("A+");
}


//02. logical OR
let mark = 50;

if(mark>=33 || mark>=80){
  console.log("pass");
  console.log("A+");
}

// logical NOT
let markss = 50;

if(!(markss<33)){
  console.log("pass");
  console.log("A+");
}